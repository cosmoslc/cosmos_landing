// DOM ready
document.addEventListener("DOMContentLoaded", function () {
  // ========== LANGUAGE SWITCHER ==========
  const languageSwitcher = document.getElementById("languageSwitcher");
  const langCurrent = document.getElementById("langCurrent");
  const langOptions = document.querySelectorAll(".lang-option");
  let currentLang = "en";

  if (langCurrent) {
    langCurrent.addEventListener("click", function (e) {
      e.stopPropagation();
      languageSwitcher.classList.toggle("active");
    });
  }

  document.addEventListener("click", function () {
    if (languageSwitcher) {
      languageSwitcher.classList.remove("active");
    }
  });

  langOptions.forEach(function (option) {
    option.addEventListener("click", function (e) {
      e.stopPropagation();
      const lang = option.getAttribute("data-lang");
      switchLanguage(lang);
      languageSwitcher.classList.remove("active");
    });
  });

  function switchLanguage(lang) {
    currentLang = lang;

    langOptions.forEach(function (opt) {
      opt.classList.remove("active");
      if (opt.getAttribute("data-lang") === lang) {
        opt.classList.add("active");
      }
    });

    const flags = { en: "🇬🇧", ru: "🇷🇺", uz: "🇺🇿" };
    const names = { en: "EN", ru: "RU", uz: "UZ" };

    const flagElement = langCurrent.querySelector(".lang-flag");
    const nameElement = langCurrent.querySelector(".lang-name");

    if (flagElement) flagElement.textContent = flags[lang];
    if (nameElement) nameElement.textContent = names[lang];

    document.documentElement.lang = lang;

    document.querySelectorAll("[data-translate]").forEach(function (element) {
      const key = element.getAttribute("data-translate");
      if (translations[lang] && translations[lang][key]) {
        if (key === "hero-title") {
          element.innerHTML = translations[lang][key];
        } else {
          element.textContent = translations[lang][key];
        }
      }
    });

    localStorage.setItem("cosmos-lc-language", lang);
  }

  const savedLang = localStorage.getItem("cosmos-lc-language");
  if (savedLang && translations[savedLang]) {
    switchLanguage(savedLang);
  }

  // ========== NAVBAR SCROLL ==========
  window.addEventListener("scroll", function () {
    const navbar = document.getElementById("navbar");
    if (navbar) {
      if (window.scrollY > 100) {
        navbar.classList.add("scrolled");
      } else {
        navbar.classList.remove("scrolled");
      }
    }
  });

  // ========== COUNTER ANIMATION ==========
  function animateCounter(element, target) {
    let current = 0;
    const increment = target / 100;
    const duration = 2000;
    const stepTime = duration / 100;

    const timer = setInterval(function () {
      current += increment;
      if (current >= target) {
        element.textContent = target + "+";
        clearInterval(timer);
      } else {
        element.textContent = Math.floor(current) + "+";
      }
    }, stepTime);
  }

  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            const numbers = entry.target.querySelectorAll(
              ".achievement-number",
            );
            numbers.forEach(function (num) {
              const target = parseInt(num.getAttribute("data-target"));
              num.textContent = "0+";
              setTimeout(function () {
                animateCounter(num, target);
              }, 200);
            });
            observer.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.5 },
    );

    const achievementsSection = document.querySelector(".achievements");
    if (achievementsSection) {
      observer.observe(achievementsSection);
    }
  }

  // ========== SMOOTH SCROLL ==========
  document.querySelectorAll('a[href^="#"]').forEach(function (anchor) {
    anchor.addEventListener("click", function (e) {
      e.preventDefault();
      const target = document.querySelector(this.getAttribute("href"));
      if (target) {
        target.scrollIntoView({
          behavior: "smooth",
          block: "start",
        });
      }
    });
  });
});
